#!/usr/bin/env node
// Builds the Mintlify site in site/ from docs/.
//
// site/ holds the hand-written pages (home, a quick start and a full guide per role) and docs.json.
// This script converts docs/how-to, docs/explanation, and docs/reference to MDX next to them
// (gitignored), rewrites links to site routes or GitHub, and fails if any page link or nav entry
// does not resolve. docs/start and docs/README.md are replaced by the hand-written pages.
//
//   node scripts/gen-site.mjs          generate, then check links and navigation
//
// Preview: cd site && npx mint dev. Deploy: .github/workflows/docs-site.yml.

import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const DOCS = path.join(ROOT, "docs");
const SITE = path.join(ROOT, "site");
const REPO = "https://github.com/tsnAnh/team-kit";
const GENERATED_DIRS = ["how-to", "explanation", "reference"];
// docs/ pages the site replaces with its own hand-written pages.
const REPLACED = {
  "README.md": "/",
  "start/engineers.md": "/quickstart/engineers",
  "start/designers.md": "/quickstart/designers",
  "start/product-and-marketing.md": "/quickstart/product-and-marketing",
  "start/founders-and-leads.md": "/quickstart/founders-and-leads",
};

const problems = [];
const report = (file, msg) => problems.push(`${file}: ${msg}`);
const rel = (p) => path.relative(ROOT, p).split(path.sep).join("/");

function routeForDocsFile(docsRel) {
  if (docsRel in REPLACED) return REPLACED[docsRel];
  const dir = docsRel.split("/")[0];
  if (GENERATED_DIRS.includes(dir) && docsRel.endsWith(".md")) return "/" + docsRel.replace(/\.md$/, "");
  return null;
}

// Rewrites one markdown link target found in docs/<fromRel>.
function rewriteTarget(target, fromFile) {
  if (/^([a-z]+:|#)/i.test(target)) return target;
  const [p, hash = ""] = target.split("#");
  const abs = path.resolve(path.dirname(fromFile), p);
  const anchor = hash ? "#" + hash : "";
  if (!fs.existsSync(abs)) {
    report(rel(fromFile), `link ${target} does not exist`);
    return target;
  }
  const repoRel = rel(abs);
  if (repoRel.startsWith("docs/")) {
    const route = routeForDocsFile(repoRel.slice("docs/".length));
    if (route) return route + anchor;
  }
  const kind = fs.statSync(abs).isDirectory() ? "tree" : "blob";
  return `${REPO}/${kind}/main/${repoRel}${anchor}`;
}

// MDX treats <, {, and } as syntax. Escape them outside code, and drop HTML comments.
function escapeProse(text) {
  return text.replace(/[<{}]/g, (c) => ({ "<": "&lt;", "{": "&#123;", "}": "&#125;" })[c]);
}

function convertBody(md, fromFile) {
  md = md.replace(/<!--[\s\S]*?-->\n?/g, "");
  const out = [];
  let inFence = false;
  for (const line of md.split("\n")) {
    if (/^\s*(```|~~~)/.test(line)) {
      inFence = !inFence;
      out.push(line);
      continue;
    }
    if (inFence) {
      out.push(line);
      continue;
    }
    // Split on inline code spans so their contents stay literal.
    const parts = line.split(/(`+[^`]*`+)/);
    out.push(
      parts
        .map((part, i) => {
          if (i % 2 === 1) return part;
          const linked = part.replace(/\]\(([^)\s]+)\)/g, (_, t) => `](${rewriteTarget(t, fromFile)})`);
          return escapeProse(linked).replace(/&lt;br&gt;/g, "<br />");
        })
        .join(""),
    );
  }
  return out.join("\n");
}

function convertFile(file) {
  const md = fs.readFileSync(file, "utf8");
  const h1 = md.match(/^# (.+)$/m);
  if (!h1) report(rel(file), "has no # title");
  const title = h1 ? h1[1].trim() : path.basename(file, ".md");
  const body = md.replace(/^# .+\n+/m, "");
  const firstPara = body
    .replace(/<!--[\s\S]*?-->/g, "")
    .split(/\n\s*\n/)
    .map((p) => p.trim())
    .find((p) => p && !/^[#|`>\-*<]/.test(p));
  const description = firstPara ? firstPara.replace(/\s+/g, " ").replace(/\[([^\]]+)\]\([^)]+\)/g, "$1").replace(/[`*]/g, "") : "";
  const front = ["---", `title: ${JSON.stringify(title)}`];
  if (description) front.push(`description: ${JSON.stringify(description.length > 160 ? description.slice(0, 157).replace(/\s+\S*$/, "") + "…" : description)}`);
  front.push("---", "");
  const source = `{/* Generated by scripts/gen-site.mjs from ${rel(file)}. Edit that file, not this one. */}\n\n`;
  return front.join("\n") + "\n" + source + convertBody(body, file).trimEnd() + "\n";
}

// 1. Generate.
for (const dir of GENERATED_DIRS) {
  fs.rmSync(path.join(SITE, dir), { recursive: true, force: true });
  const srcDir = path.join(DOCS, dir);
  for (const name of fs.readdirSync(srcDir).filter((n) => n.endsWith(".md")).sort()) {
    const outFile = path.join(SITE, dir, name.replace(/\.md$/, ".mdx"));
    fs.mkdirSync(path.dirname(outFile), { recursive: true });
    fs.writeFileSync(outFile, convertFile(path.join(srcDir, name)));
  }
}

// 2. Every docs page is either generated or replaced by a hand-written page.
for (const dir of fs.readdirSync(DOCS, { withFileTypes: true })) {
  if (!dir.isDirectory()) continue;
  for (const name of fs.readdirSync(path.join(DOCS, dir.name)).filter((n) => n.endsWith(".md"))) {
    if (!routeForDocsFile(`${dir.name}/${name}`)) report(`docs/${dir.name}/${name}`, "has no page on the site; add its folder to GENERATED_DIRS or REPLACED in scripts/gen-site.mjs");
  }
}

// 3. Navigation lists every page exactly once, and every listed page exists.
const config = JSON.parse(fs.readFileSync(path.join(SITE, "docs.json"), "utf8"));
const navPages = [];
(function walk(node) {
  if (Array.isArray(node)) return node.forEach(walk);
  if (typeof node === "string") return navPages.push(node);
  if (node && typeof node === "object") for (const [k, v] of Object.entries(node)) if (["pages", "groups", "tabs", "navigation"].includes(k)) walk(v);
})(config.navigation);
const pageFiles = new Set();
(function collect(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name);
    if (e.isDirectory() && e.name !== "node_modules" && !e.name.startsWith(".")) collect(full);
    else if (e.name.endsWith(".mdx")) pageFiles.add(path.relative(SITE, full).split(path.sep).join("/").replace(/\.mdx$/, ""));
  }
})(SITE);
const seen = new Set();
for (const p of navPages) {
  if (seen.has(p)) report("site/docs.json", `lists ${p} twice`);
  seen.add(p);
  if (!pageFiles.has(p)) report("site/docs.json", `lists ${p}, which has no .mdx file`);
}
for (const p of pageFiles) if (!seen.has(p)) report(`site/${p}.mdx`, "is not in docs.json navigation");

// 4. Every internal link on every page points at a page (anchors are not checked).
const routes = new Set([...pageFiles].map((p) => (p === "index" ? "/" : "/" + p)));
for (const p of pageFiles) {
  const text = fs.readFileSync(path.join(SITE, p + ".mdx"), "utf8");
  for (const m of text.matchAll(/(?:\]\(|href=")(\/[^)"#\s]*)/g)) {
    const route = m[1].replace(/\/$/, "") || "/";
    if (!routes.has(route)) report(`site/${p}.mdx`, `links to ${m[1]}, which is not a page`);
  }
}

if (problems.length) {
  console.error(problems.map((p) => "✗ " + p).join("\n"));
  process.exit(1);
}
console.log(`site: ${pageFiles.size} pages, links and navigation resolve`);
