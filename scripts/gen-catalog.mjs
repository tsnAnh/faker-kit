#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { ROOT, listSkills, marketplacePlugins, parseFrontmatter } from "./lib/skills.mjs";

const CATALOG = "docs/catalog.json";
const OUTPUTS = { skills: "docs/reference/skills.md", coverage: "docs/reference/coverage.md", playbooks: "docs/reference/playbooks.md", packs: "docs/reference/lint-packs.md" };
const PACKS = "plugins/trust-ladder/packs";
const PACK_ORDER = ["agnostic", "kotlin-android", "kmp", "rust", "python", "flutter-dart", "swift-ios"];
const FAKER_MODE = "plugins/pstack/skills/faker-mode";
const OWN_PLUGIN = "trust-ladder";
const AUDIENCES = { everyone: "Everyone", engineer: "Engineers", lead: "Leads" };
const SOURCES = {
  talk: "Lauren Tan's talk on building trust in agents",
  pt1: "The Complete Guide to pstack, Pt. 1",
  pt2: "The Complete Guide to pstack, Pt. 2",
  pstack: "Named inside pstack but built into Cursor",
};
const HEADER = "<!-- Generated by scripts/gen-catalog.mjs from docs/catalog.json and each SKILL.md. Edit those, then run `node scripts/gen-catalog.mjs`. -->";

const readCatalog = () => JSON.parse(fs.readFileSync(path.join(ROOT, CATALOG), "utf8"));

function escapeText(text) {
  return text
    .split(/(`[^`]*`)/)
    .map((part, i) => (i % 2 === 1 ? part : part.replace(/</g, "&lt;").replace(/>/g, "&gt;")))
    .join("");
}

const escapeCell = (text) => escapeText(text).replace(/\|/g, "\\|");

function firstSentence(text) {
  const clean = (text ?? "").replace(/\s+/g, " ").trim();
  const match = /^(.+?[.!?])(?:\s|$)/.exec(clean);
  const sentence = match ? match[1] : clean;
  if (sentence.length <= 220) return sentence;
  return `${sentence.slice(0, 217).replace(/\s+\S*$/, "")}...`;
}

function skillLink(skill, fromDir) {
  const target = path.relative(path.join(ROOT, fromDir), path.join(skill.dir, "SKILL.md")).split(path.sep).join("/");
  return `[${skill.name}](${target})`;
}

function crossPluginReferences(skills) {
  const textOf = new Map();
  const files = (dir) =>
    fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
      if (e.name === "node_modules" || e.name.startsWith(".")) return [];
      const full = path.join(dir, e.name);
      if (e.isDirectory()) return files(full);
      return /\.(md|mdc)$/.test(e.name) ? [full] : [];
    });
  const pluginText = (plugin) => {
    if (!textOf.has(plugin)) textOf.set(plugin, files(path.join(ROOT, "plugins", plugin)).map((f) => fs.readFileSync(f, "utf8")).join("\n"));
    return textOf.get(plugin);
  };
  const referencedBy = new Map();
  for (const plugin of marketplacePlugins()) {
    if (plugin === OWN_PLUGIN) continue;
    for (const skill of skills) {
      if (skill.plugin === plugin) continue;
      const name = skill.name.replace(/[-]/g, "\\-");
      const pattern = new RegExp(`(\`/?${name}\`|(?:^|[\\s(])/${name}\\b|\\*\\*${name}\\*\\*|\\b${name} skill)`, "m");
      if (pattern.test(pluginText(plugin))) {
        const list = referencedBy.get(skill.key) ?? [];
        list.push(plugin);
        referencedBy.set(skill.key, list);
      }
    }
  }
  return referencedBy;
}

function renderSkills(catalog, skills) {
  const byKey = new Map(skills.map((s) => [s.key, s]));
  const plugins = new Set(skills.map((s) => s.plugin));
  const out = [
    HEADER,
    "",
    "# Skills",
    "",
    `Every skill in the kit: ${skills.length} skills from ${plugins.size} plugins, grouped by the layer of the trust ladder it strengthens. See [the trust ladder](../explanation/trust-ladder.md) for what the layers mean.`,
    "",
    "## How to call a skill",
    "",
    "The examples below are written for Claude Code. In the other agents, change the first word:",
    "",
    "| Claude Code | Codex | Pi |",
    "|---|---|---|",
    "| `/faker-mode` or `/pstack:faker-mode` | `$faker-mode` | `/skill:faker-mode` |",
    "",
    "You rarely need the name. Each agent picks a skill on its own when your request matches the skill's description, so \"verify it really works\" is often enough. Call a skill by name when you want to be sure.",
    "",
    "**For** says who the skill is written for. **Everyone** means you do not need to read code to use it.",
    "",
  ];
  for (const [layer, title] of Object.entries(catalog.layers)) {
    const rows = Object.entries(catalog.skills).filter(([, entry]) => entry.layer === layer);
    if (rows.length === 0) continue;
    out.push(`## ${title}`, "", "| Skill | Plugin | For | Try | What it does |", "|---|---|---|---|---|");
    for (const [key, entry] of rows) {
      const skill = byKey.get(key);
      if (!skill) continue;
      const audience = entry.audience.map((a) => AUDIENCES[a]).join(", ");
      out.push(`| ${skillLink(skill, "docs/reference")} | ${skill.plugin} | ${audience} | \`${entry.prompt}\` | ${escapeCell(firstSentence(skill.fields.description))} |`);
    }
    out.push("");
  }
  out.push(
    "## Dormant: the benny automation pack",
    "",
    "pstack ships an issue-report bot as an automation pack. Its skills are not loaded until you set it up, because they need a feedback channel and a bot identity. Point your agent at [`FOR_AGENTS.md`](../../plugins/pstack/automations/benny/FOR_AGENTS.md) to install it.",
    "",
    "| Skill | Try | What it does |",
    "|---|---|---|",
  );
  for (const [key, entry] of Object.entries(catalog.dormant)) {
    const dir = path.join(ROOT, "plugins", key);
    const fields = listSkillFields(dir);
    const skill = { name: path.basename(dir), dir };
    out.push(`| ${skillLink(skill, "docs/reference")} | \`${entry.prompt}\` | ${escapeCell(firstSentence(fields.description))} |`);
  }
  out.push("");
  return out.join("\n");
}

function listSkillFields(dir) {
  const file = path.join(dir, "SKILL.md");
  return fs.existsSync(file) ? (parseFrontmatter(fs.readFileSync(file, "utf8")) ?? {}) : {};
}

function renderCoverage(catalog, skills) {
  const byKey = new Map(skills.map((s) => [s.key, s]));
  const referencedBy = crossPluginReferences(skills);
  const named = Object.values(catalog.skills).filter((e) => e.mentioned.length > 0).length;
  const out = [
    HEADER,
    "",
    "# Coverage",
    "",
    "Where everything in Lauren Tan's talk and her two pstack guide posts lives in this kit, plus every skill those skills reference. `node scripts/validate.mjs` fails if a skill in the kit is missing from the catalog, so this page cannot fall behind.",
    "",
    `- ${skills.length} skills from ${new Set(skills.map((s) => s.plugin)).size} plugins, plus ${Object.keys(catalog.dormant).length} dormant automation skills.`,
    `- ${named} skills are named in the posts, and all of them are here.`,
    `- ${catalog.mentions.length} ideas, bots, and tools from the talk and posts are mapped to the skills that carry them.`,
    "",
  ];
  for (const source of ["talk", "pt1", "pt2"]) {
    out.push(`## ${SOURCES[source]}`, "");
    const skillRows = Object.entries(catalog.skills).filter(([, entry]) => entry.mentioned.includes(source));
    if (skillRows.length === 0) {
      out.push("It names no skill by name. Everything it describes is mapped below.", "");
    } else {
      out.push("Skills it names:", "", "| Skill | Plugin |", "|---|---|");
      for (const [key, entry] of skillRows) {
        const skill = byKey.get(key);
        const renamed = entry.renamedFrom ? ` (named \`${entry.renamedFrom}\` there)` : "";
        if (skill) out.push(`| ${skillLink(skill, "docs/reference")}${renamed} | ${skill.plugin} |`);
      }
      out.push("");
    }
    out.push("What it describes:", "", "| Idea or tool | In this kit |", "|---|---|");
    for (const mention of catalog.mentions.filter((m) => m.source === source)) {
      out.push(`| ${escapeCell(mention.what)} | ${escapeCell(mention.where)} |`);
    }
    out.push("");
  }
  out.push(`## ${SOURCES.pstack}`, "", "| Named | In this kit |", "|---|---|");
  for (const mention of catalog.mentions.filter((m) => m.source === "pstack")) out.push(`| ${escapeCell(mention.what)} | ${escapeCell(mention.where)} |`);
  out.push(
    "",
    "## Skills referenced across plugins",
    "",
    "Found by scanning each vendored plugin for another plugin's skill names. Each referenced skill is included, so a pstack step that says \"use `control-ui`\" works.",
    "",
    "| Skill | Lives in | Referenced by |",
    "|---|---|---|",
  );
  for (const [key, referrers] of [...referencedBy].sort(([a], [b]) => a.localeCompare(b))) {
    const skill = byKey.get(key);
    out.push(`| ${skillLink(skill, "docs/reference")} | ${skill.plugin} | ${referrers.join(", ")} |`);
  }
  out.push("", "## Plugins in the kit", "", "| Plugin | Skills | Why it is here |", "|---|---|---|");
  for (const plugin of marketplacePlugins()) {
    const count = skills.filter((s) => s.plugin === plugin).length;
    out.push(`| ${plugin} | ${count} | ${escapeCell(catalog.plugins[plugin] ?? "")} |`);
  }
  out.push("", "## Left out on purpose", "", "From [cursor/plugins](https://github.com/cursor/plugins):", "", "| Plugin | Why |", "|---|---|");
  for (const item of catalog.excluded) out.push(`| ${item.plugin} | ${escapeCell(item.reason)} |`);
  out.push("");
  return out.join("\n");
}

export function playbookRoutes() {
  const text = fs.readFileSync(path.join(ROOT, FAKER_MODE, "SKILL.md"), "utf8");
  const routes = [];
  for (const line of text.split("\n")) {
    const match = /^- \*\*(.+?)\.\*\* (.*?)\s*(?:Full steps: )?`(playbooks\/[\w-]+\.md)`\.?\s*$/.exec(line);
    if (match) routes.push({ name: match[1], when: match[2].trim(), file: match[3] });
  }
  return routes;
}

function renderPlaybooks(skills) {
  const routes = playbookRoutes();
  const principles = skills.filter((s) => s.plugin === "pstack" && s.name.startsWith("principle-"));
  const out = [
    HEADER,
    "",
    "# Playbooks and principles",
    "",
    `\`/faker-mode\` classifies each task and loads one of these ${routes.length} playbooks. You do not pick them; describing the task is enough. Naming one ("use the prototype playbook") forces the choice. The list below is read from [faker-mode's SKILL.md](../../${FAKER_MODE}/SKILL.md), so it stays current with pstack.`,
    "",
    "| Playbook | faker-mode uses it for |",
    "|---|---|",
  ];
  for (const route of routes) {
    out.push(`| [${route.name}](../../${FAKER_MODE}/${route.file}) | ${escapeCell(route.when)} |`);
  }
  out.push(
    "",
    "## Principles",
    "",
    `pstack's ${principles.length} principles are skills that playbooks call by name, such as "the **prove-it-works** principle skill". Name one in a prompt to apply it on purpose.`,
    "",
    "| Principle | When to apply it |",
    "|---|---|",
  );
  for (const skill of principles) {
    out.push(`| ${skillLink(skill, "docs/reference")} | ${escapeCell(firstSentence(skill.fields.description))} |`);
  }
  out.push("");
  return out.join("\n");
}

function detectText(detect) {
  if (detect.always) return "Every repository";
  const parts = [];
  if (detect.files) parts.push(detect.files.map((f) => `\`${f}\``).join(" or "));
  if (detect.globs) parts.push(detect.globs.map((f) => `\`${f}\``).join(" or "));
  let text = parts.join(", or ");
  if (detect.contains) text += ` containing ${detect.contains.map((c) => `\`${c}\``).join(" or ")}`;
  return text;
}

function renderPacks() {
  const names = fs.readdirSync(path.join(ROOT, PACKS), { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name);
  const ordered = [...PACK_ORDER.filter((n) => names.includes(n)), ...names.filter((n) => !PACK_ORDER.includes(n)).sort()];
  const packs = ordered.map((name) => JSON.parse(fs.readFileSync(path.join(ROOT, PACKS, name, "pack.json"), "utf8")));
  const out = [
    HEADER,
    "",
    "# Lint packs",
    "",
    "Each pack is a tested set of lint rules, compiler settings, and CI checks aimed at the mistakes agents make in that stack. Every rule fails with a message that says what to do instead, because that message is what the next agent reads. Each pack has `fixtures/bad` that must fail and `fixtures/good` that must pass, and this repository's CI runs both.",
    "",
    "Install a pack with `/setup-lint-pack <name>`, or let `/setup-team-kit` pick packs from the stacks it detects. Existing violations go into a baseline, so only new ones fail. To add a rule for a mistake the pack does not cover, use `/encode-lint-rule`.",
    "",
    "| Pack | Installed when the repository has | What it enforces |",
    "|---|---|---|",
  ];
  for (const pack of packs) {
    out.push(`| [${pack.name}](../../${PACKS}/${pack.name}/README.md) | ${escapeCell(detectText(pack.detect))} | ${escapeCell(pack.description)} |`);
  }
  for (const pack of packs) {
    out.push("", `## ${pack.name}`, "", escapeText(pack.description), "");
    if (pack.requires?.length) out.push(`Requires: ${pack.requires.map((r) => `[${r}](#${r})`).join(", ")}.`, "");
    out.push("Checks added to `scripts/check.sh`:", "", "```bash", ...pack.check, "```", "");
    if (pack.optionalChecks) {
      out.push("Optional checks, added with `--with <name>`:", "");
      for (const [name, command] of Object.entries(pack.optionalChecks)) out.push(`- \`${name}\`: \`${command}\``);
      out.push("");
    }
    out.push("Tools:", "");
    for (const tool of pack.tools) out.push(`- ${tool.name} ${tool.version}${tool.optional ? " (optional)" : ""}: ${tool.why}`);
    out.push("", `Existing violations: ${escapeText(pack.baseline)}`, "", `Details and the full rule list: [${pack.name} README](../../${PACKS}/${pack.name}/README.md).`);
  }
  out.push("");
  return out.join("\n");
}

export function render(catalog = readCatalog(), skills = listSkills()) {
  return {
    [OUTPUTS.skills]: renderSkills(catalog, skills),
    [OUTPUTS.coverage]: renderCoverage(catalog, skills),
    [OUTPUTS.playbooks]: renderPlaybooks(skills),
    [OUTPUTS.packs]: renderPacks(),
  };
}

export function catalogProblems() {
  const problems = [];
  const catalog = readCatalog();
  const skills = listSkills();
  const keys = new Set(skills.map((s) => s.key));
  for (const key of keys) if (!catalog.skills[key]) problems.push(`${CATALOG}: skill ${key} has no entry`);
  for (const [key, entry] of Object.entries(catalog.skills)) {
    if (!keys.has(key)) problems.push(`${CATALOG}: ${key} is not a skill in the marketplace`);
    if (!catalog.layers[entry.layer]) problems.push(`${CATALOG}: ${key} has unknown layer "${entry.layer}"`);
    if (!entry.audience?.length || entry.audience.some((a) => !AUDIENCES[a])) problems.push(`${CATALOG}: ${key} audience must be a non-empty subset of ${Object.keys(AUDIENCES).join(", ")}`);
    if (!entry.prompt) problems.push(`${CATALOG}: ${key} has no example prompt`);
    if (!Array.isArray(entry.mentioned) || entry.mentioned.some((m) => !["talk", "pt1", "pt2"].includes(m))) problems.push(`${CATALOG}: ${key} mentioned must list talk, pt1, or pt2`);
  }
  for (const key of Object.keys(catalog.dormant)) {
    if (!fs.existsSync(path.join(ROOT, "plugins", key, "SKILL.md"))) problems.push(`${CATALOG}: dormant skill plugins/${key}/SKILL.md does not exist`);
  }
  for (const mention of catalog.mentions) {
    if (!SOURCES[mention.source]) problems.push(`${CATALOG}: mention "${mention.what}" has unknown source "${mention.source}"`);
  }
  for (const plugin of marketplacePlugins()) {
    if (!catalog.plugins[plugin]) problems.push(`${CATALOG}: plugin ${plugin} has no reason in "plugins"`);
  }
  const playbooks = fs.readdirSync(path.join(ROOT, FAKER_MODE, "playbooks")).filter((f) => f.endsWith(".md"));
  const routed = new Set(playbookRoutes().map((r) => path.basename(r.file)));
  for (const file of playbooks) if (!routed.has(file)) problems.push(`${FAKER_MODE}/playbooks/${file}: not found in faker-mode's routing list; update playbookRoutes()`);
  if (problems.length > 0) return problems;
  for (const [file, content] of Object.entries(render(catalog, skills))) {
    const full = path.join(ROOT, file);
    if (!fs.existsSync(full) || fs.readFileSync(full, "utf8") !== content) problems.push(`${file}: out of date; run node scripts/gen-catalog.mjs`);
  }
  return problems;
}

function main() {
  const check = process.argv.includes("--check");
  if (check) {
    const problems = catalogProblems();
    if (problems.length > 0) {
      process.stderr.write(`gen-catalog: ${problems.length} problem(s)\n  ${problems.join("\n  ")}\n`);
      process.exit(1);
    }
    process.stdout.write("gen-catalog: docs are current\n");
    return;
  }
  for (const [file, content] of Object.entries(render())) {
    fs.mkdirSync(path.dirname(path.join(ROOT, file)), { recursive: true });
    fs.writeFileSync(path.join(ROOT, file), content);
    process.stdout.write(`wrote ${file}\n`);
  }
  const problems = catalogProblems();
  if (problems.length > 0) {
    process.stderr.write(`gen-catalog: ${problems.length} problem(s)\n  ${problems.join("\n  ")}\n`);
    process.exit(1);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
